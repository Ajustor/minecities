"""Génère le modèle de l'hôtel de ville : un bâtiment miniature en blocs vanilla, à la manière des
huttes de MineColonies. Conçu dans Blockbench (MCP), puis reporté ici pour rester modifiable.

Usage : python tools/models/town_hall.py
Écrit src/main/resources/assets/minecities/models/block/town_hall.json. Le modèle regarde vers le
nord (la porte en z = 0) ; l'état de bloc le tourne selon FACING.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "src/main/resources/assets/minecities/models/block/town_hall.json"

TEXTURES = {
    "stone": "minecraft:block/stone_bricks",
    "planks": "minecraft:block/oak_planks",
    "roof": "minecraft:block/spruce_planks",
    "post": "minecraft:block/stripped_oak_log",
    "door": "minecraft:block/dark_oak_planks",
    "banner": "minecraft:block/blue_wool",
    "gold": "minecraft:block/gold_block",
    "glass": "minecraft:block/light_blue_stained_glass",
}

# (nom, de, à, texture)
ELEMENTS = [
    ("foundation", (0, 0, 0), (16, 3, 16), "stone"),
    ("walls", (1.5, 3, 1.5), (14.5, 10, 14.5), "planks"),
    ("post_nw", (1, 3, 1), (3, 10, 3), "post"),
    ("post_ne", (13, 3, 1), (15, 10, 3), "post"),
    ("post_sw", (1, 3, 13), (3, 10, 15), "post"),
    ("post_se", (13, 3, 13), (15, 10, 15), "post"),
    ("roof_1", (0, 10, 0), (16, 11.5, 16), "roof"),
    ("roof_2", (2, 11.5, 2), (14, 13, 14), "roof"),
    ("roof_3", (4, 13, 4), (12, 14, 12), "roof"),
    ("door", (6.5, 3, 1), (9.5, 7.5, 1.5), "door"),
    ("belfry_post", (7.25, 14, 7.25), (8.75, 15, 8.75), "door"),
    ("banner", (5.5, 7.75, 1.1), (10.5, 9.75, 1.5), "banner"),
    ("emblem", (7.5, 8.25, 0.9), (8.5, 9.25, 1.1), "gold"),
    ("bell", (6.75, 14.5, 6.75), (9.25, 16, 9.25), "gold"),
    ("door_knob", (8.75, 5, 0.8), (9.25, 5.5, 1), "gold"),
    ("window_w", (1.25, 5, 6), (1.5, 8, 10), "glass"),
    ("window_e", (14.5, 5, 6), (14.75, 8, 10), "glass"),
    ("window_s", (6, 5, 14.5), (10, 8, 14.75), "glass"),
    ("window_nl", (3.5, 5, 1.25), (5.5, 7.5, 1.5), "glass"),
    ("window_nr", (10.5, 5, 1.25), (12.5, 7.5, 1.5), "glass"),
]


def num(v):
    return int(v) if float(v).is_integer() else v


def faces(frm, to, texture):
    """Des UV « auto » comme Blockbench : chaque face prend un morceau de texture à sa taille."""
    dx, dy, dz = (to[i] - frm[i] for i in range(3))
    sizes = {"north": (dx, dy), "south": (dx, dy), "east": (dz, dy), "west": (dz, dy),
             "up": (dx, dz), "down": (dx, dz)}
    out = {}
    for face, (w, h) in sizes.items():
        entry = {"uv": [0, 0, num(w), num(h)], "texture": "#" + texture}
        if face == "down" and frm[1] == 0:
            entry["cullface"] = "down"
        out[face] = entry
    return out


def main():
    model = {
        "credit": "Made with Blockbench, generated by tools/models/town_hall.py",
        "parent": "minecraft:block/block",
        "textures": {"particle": TEXTURES["planks"], **TEXTURES},
        "elements": [
            {"name": name, "from": [num(v) for v in frm], "to": [num(v) for v in to], "faces": faces(frm, to, tex)}
            for name, frm, to, tex in ELEMENTS
        ],
    }
    text = json.dumps(model, indent="\t")
    # Les listes de nombres et les faces tiennent sur une ligne, comme dans les exports de Blockbench.
    text = re.sub(r"\[\s+([^\[\]{}]+?)\s+\]",
                  lambda m: "[" + ", ".join(x.strip() for x in m.group(1).split(",")) + "]", text)
    text = re.sub(r"\{\s+(\"uv\"[^{}]+?)\s+\}", lambda m: "{" + " ".join(m.group(1).split()) + "}", text)
    OUT.write_text(text + "\n", encoding="utf-8", newline="\n")
    print(OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
